import type { Request } from 'express';
import { z } from 'zod';
import { ComposeMockInput, composeMockSchema, libraryVisibilitySchema } from '@ielts/validation';
import { AuditService } from '../audit/audit.service';
import { notFound } from '../common/app-error';
import { AuthUser, CurrentUser, RequirePermission, clientMeta } from '../common/decorators';
import { ZodPipe } from '../common/zod.pipe';
import { RotationService } from '../question-bank/rotation.service';
import { PrismaService } from '../prisma/prisma.service';
import { QuestionBankModule } from '../question-bank/question-bank.module';

type Actor = { userId: string; ip?: string; userAgent?: string };
const uuid = new ParseUUIDPipe();
const listQuery = z.object({
  skip: z.coerce.number().int().min(0).default(0),
  take: z.coerce.number().int().min(1).max(100).default(25),
  includeArchived: z.coerce.boolean().optional().default(false),
});

/**
 * Composes a whole-module mock test: one click picks the least-used published Listening module and
 * the least-used published Reading module (RotationService — the same picker free-test uses, so
 * both features share one usage counter), resolves/reuses each one's wrapper Assessment, and
 * publishes the result as a MockExam that's immediately library-visible — collapsing the old
 * compose → publish → show-in-library sequence into one step. Nothing is generated by AI, and
 * nothing is manually configured: no count/difficulty/topic form, matching the brief's "automatic
 * rotation of compatible modules" requirement.
 *
 * Writing/Speaking are not part of a MockExam — they stay on SimulatorService's existing per-
 * attempt random pick from the bank (see MockExam's schema comment for why).
 */
@Injectable()
export class MockExamsService {
  constructor(private readonly prisma: PrismaService, private readonly rotation: RotationService, private readonly audit: AuditService) {}

  async compose(input: ComposeMockInput, actor: Actor) {
    const [listeningSetId, readingSetId] = input.listeningSetId && input.readingSetId
      ? await this.assertManualSets(input.listeningSetId, input.readingSetId)
      : await this.prisma.$transaction(async (tx) => {
          await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext('mock_exam_assign'))`;
          return Promise.all([this.rotation.pickLeastUsedBankSet(tx, 'LISTENING'), this.rotation.pickLeastUsedBankSet(tx, 'READING')]);
        });
    const [listeningAssessmentId, readingAssessmentId] = await Promise.all([
      this.rotation.resolveWrapperAssessment(listeningSetId, 'LISTENING'),
      this.rotation.resolveWrapperAssessment(readingSetId, 'READING'),
    ]);

    // Validate any pinned Writing / Speaking questions.
    const wsIds = {
      writingTask1QuestionId: input.writingTask1QuestionId,
      writingTask2QuestionId: input.writingTask2QuestionId,
      speakingPart1QuestionId: input.speakingPart1QuestionId,
      speakingPart2QuestionId: input.speakingPart2QuestionId,
      speakingPart3QuestionId: input.speakingPart3QuestionId,
    };
    const wsEntries = Object.entries(wsIds).filter((e): e is [string, string] => !!e[1]);
    if (wsEntries.length) await this.assertWritingSpeakingQuestions(wsEntries);

    const mockExam = await this.prisma.mockExam.create({
      data: {
        title: input.title, listeningSetId, readingSetId, listeningAssessmentId, readingAssessmentId,
        status: 'PUBLISHED', libraryVisible: true, ...Object.fromEntries(wsEntries),
      },
    });
    await this.audit.record({ ...actor, action: 'ADMIN_COMPOSED_MOCK_EXAM', entityType: 'MockExam', entityId: mockExam.id, after: { listeningSetId, readingSetId, ...Object.fromEntries(wsEntries) } });
    return mockExam;
  }

  /** Validates a manually-chosen pair before composing with them: both must be published,
   *  student-facing bank sets of the expected skill. */
  private async assertManualSets(listeningSetId: string, readingSetId: string): Promise<[string, string]> {
    const [listening, reading] = await Promise.all([
      this.prisma.questionSet.findUnique({ where: { id: listeningSetId }, select: { skill: true, status: true, studentFacing: true } }),
      this.prisma.questionSet.findUnique({ where: { id: readingSetId }, select: { skill: true, status: true, studentFacing: true } }),
    ]);
    const ok = (s: typeof listening, skill: 'LISTENING' | 'READING') => !!s && s.skill === skill && s.status === 'PUBLISHED' && s.studentFacing;
    if (!ok(listening, 'LISTENING')) throw notFound('Listening module');
    if (!ok(reading, 'READING')) throw notFound('Reading module');
    return [listeningSetId, readingSetId];
  }

  /** Validates pinned Writing / Speaking questions — must exist, not be deleted, and have the
   *  expected ieltsType for their slot. */
  private async assertWritingSpeakingQuestions(entries: [string, string][]) {
    const EXPECTED_TYPES: Record<string, string[]> = {
      writingTask1QuestionId:  ['WRITING_TASK1'],
      writingTask2QuestionId:  ['WRITING_TASK2'],
      speakingPart1QuestionId: ['SPEAKING_PART1'],
      speakingPart2QuestionId: ['SPEAKING_PART2'],
      speakingPart3QuestionId: ['SPEAKING_PART3'],
    };
    await Promise.all(entries.map(async ([field, id]) => {
      const q = await this.prisma.question.findUnique({ where: { id }, select: { ieltsType: true, deletedAt: true } });
      if (!q || q.deletedAt) throw notFound(`${field.replace('QuestionId', '')} question`);
      const allowed = EXPECTED_TYPES[field];
      if (allowed && q.ieltsType && !allowed.includes(q.ieltsType)) {
        throw notFound(`${field.replace('QuestionId', '')} question (wrong type: ${q.ieltsType})`);
      }
    }));
  }

  /** Returns selectable Writing and Speaking questions for the manual compose form.
   *  Returns id, ieltsType, and a short prompt excerpt for display. */
  async writingSpeakingCandidates() {
    const questions = await this.prisma.question.findMany({
      where: {
        deletedAt: null,
        ieltsType: { in: ['WRITING_TASK1', 'WRITING_TASK2', 'SPEAKING_PART1', 'SPEAKING_PART2', 'SPEAKING_PART3'] },
      },
      select: { id: true, ieltsType: true, versions: { orderBy: { version: 'desc' }, take: 1, select: { prompt: true } } },
      orderBy: { createdAt: 'desc' },
      take: 500,
    });
    return questions.map((q) => {
      const prompt = q.versions[0]?.prompt;
      // Extract a short text excerpt from the prompt JSON (best-effort).
      let excerpt = '';
      if (prompt && typeof prompt === 'object') {
        const text = (prompt as Record<string, unknown>).text ?? (prompt as Record<string, unknown>).body;
        if (typeof text === 'string') excerpt = text.slice(0, 120).trim();
      }
      return { id: q.id, ieltsType: q.ieltsType, excerpt };
    });
  }

  /** The admin-facing list, enriched with each mock's module titles and how many simulator attempts
   *  it has produced, so admins can see real usage before deciding what to hide or archive.
   *  Archived mocks are hidden by default; pass includeArchived=true to show them. */
  async list(q: { skip: number; take: number; includeArchived: boolean }) {
    const where = q.includeArchived ? {} : { status: { not: 'ARCHIVED' as const } };
    const [items, total] = await Promise.all([
      this.prisma.mockExam.findMany({
        where, orderBy: { createdAt: 'desc' }, skip: q.skip, take: q.take,
        select: {
          id: true, title: true, status: true, libraryVisible: true, createdAt: true,
          listeningSet: { select: { title: true } }, readingSet: { select: { title: true } },
          listeningAssessmentId: true, readingAssessmentId: true,
        },
      }),
      this.prisma.mockExam.count({ where }),
    ]);
    // Exclude ghost (free-test) students from attempt counts so they don't inflate admin numbers.
    const counts = await Promise.all(items.map((m) => this.prisma.examAttempt.count({
      where: { listeningAssessmentId: m.listeningAssessmentId, readingAssessmentId: m.readingAssessmentId, student: { isGhost: false } },
    })));
    return {
      items: items.map((m, i) => ({
        id: m.id, title: m.title, status: m.status, libraryVisible: m.libraryVisible, createdAt: m.createdAt,
        listeningModuleTitle: m.listeningSet.title, readingModuleTitle: m.readingSet.title, attemptsCount: counts[i],
      })),
      total,
    };
  }

  /** Hiding it from the library never affects attempts already made or in-flight access requests. */
  async setLibraryVisible(id: string, visible: boolean, actor: Actor) {
    return this.prisma.$transaction(async (tx) => {
      const m = await tx.mockExam.findUnique({ where: { id } });
      if (!m) throw notFound('Mock exam');
      const after = await tx.mockExam.update({ where: { id }, data: { libraryVisible: visible } });
      await this.audit.record({ ...actor, action: 'ADMIN_CHANGED_MOCK_LIBRARY', entityType: 'MockExam', entityId: id, before: { libraryVisible: m.libraryVisible }, after: { libraryVisible: visible } }, tx);
      return { id: after.id, libraryVisible: after.libraryVisible };
    });
  }

  /** Archives a mock: it disappears from the student library but in-progress attempts can still
   *  finish and past results remain viewable. Archiving is always safe — we never hard-delete a
   *  MockExam because the underlying assessment rows are shared with student history. */
  async remove(id: string, actor: Actor) {
    return this.prisma.$transaction(async (tx) => {
      const m = await tx.mockExam.findUnique({ where: { id } });
      if (!m) throw notFound('Mock exam');
      if (m.status === 'ARCHIVED') return { id, archived: true }; // already done
      await tx.mockExam.update({ where: { id }, data: { status: 'ARCHIVED', libraryVisible: false } });
      await this.audit.record({ ...actor, action: 'ADMIN_ARCHIVED_MOCK_EXAM', entityType: 'MockExam', entityId: id, before: { status: m.status }, after: { status: 'ARCHIVED' } }, tx);
      return { id, archived: true };
    });
  }
}

const actorOf = (u: AuthUser, req: Request): Actor => ({ userId: u.id, ...clientMeta(req) });

@Controller('admin/mock-exams')
export class MockExamsController {
  constructor(private readonly mocks: MockExamsService) {}

  @RequirePermission('assessment.manage') @Get()
  list(@Query(new ZodPipe(listQuery)) q: z.infer<typeof listQuery>) { return this.mocks.list(q); }

  /** Selectable Writing and Speaking questions for the manual compose form. */
  @RequirePermission('assessment.manage') @Get('writing-speaking-candidates')
  writingSpeakingCandidates() { return this.mocks.writingSpeakingCandidates(); }

  @RequirePermission('assessment.manage') @Post('compose')
  compose(@Body(new ZodPipe(composeMockSchema)) body: ComposeMockInput, @CurrentUser() u: AuthUser, @Req() req: Request) {
    return this.mocks.compose(body, actorOf(u, req));
  }

  @RequirePermission('assessment.manage') @HttpCode(200) @Post(':id/library')
  library(@Param('id', uuid) id: string, @Body(new ZodPipe(libraryVisibilitySchema)) body: { visible: boolean }, @CurrentUser() u: AuthUser, @Req() req: Request) {
    return this.mocks.setLibraryVisible(id, body.visible, actorOf(u, req));
  }

  @RequirePermission('assessment.manage') @HttpCode(200) @Delete(':id')
  remove(@Param('id', uuid) id: string, @CurrentUser() u: AuthUser, @Req() req: Request) {
    return this.mocks.remove(id, actorOf(u, req));
  }
}

@Module({
  imports: [QuestionBankModule],
  controllers: [MockExamsController],
  providers: [MockExamsService],
  exports: [MockExamsService],
})
export class MockExamsModule {}
